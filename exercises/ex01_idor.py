"""
练习 1：亲手构造一次「越权访问他人数据」

运行：python ex01_idor.py
不需要装任何东西，不需要 Docker，不需要启动你的项目。
"""
import json

# ---------------------------------------------------------------
# 模拟数据库：两个用户，各自有健康数据
# ---------------------------------------------------------------
DB = {
    "attacker_001": {"name": "张三", "record": "青霉素过敏"},
    "victim_001":   {"name": "李四", "record": "HIV 阳性 / 肝功能异常"},
}

# ---------------------------------------------------------------
# 现在模拟：你的服务器收到一个请求
# ---------------------------------------------------------------

# 第 1 步：认证层。校验 JWT 签名 → 通过，拿到"请求方是谁"
token_uid = "attacker_001"          # 攻击者本人。认证是完全合法的

# 第 2 步：解析请求体。攻击者在 JSON 里多加了一个字段
body = {
    "message": "我最近身体怎么样",
    "user_id": "victim_001",        # 攻击者自己加的字段
}

# 第 3 步：业务代码决定"以谁的身份"查数据
#         ↑ 这一行是从 frontend/hostAgentAPI/api.py:5291 复制来的
user_id = token_uid or body.get("user_id") or "default_user"

# 第 4 步：查库，返回结果
result = DB.get(user_id, {})

# ---------------------------------------------------------------
# 输出
# ---------------------------------------------------------------
print("请求方(已认证)      :", token_uid)
print("最终以谁的身份查库  :", user_id)
print("返回给请求方的数据  :", json.dumps(result, ensure_ascii=False))
print()
if user_id != token_uid:
    print(">>> 越权成功：认证的是 attacker_001，拿到的是 victim_001 的数据")
else:
    print(">>> 未越权")
